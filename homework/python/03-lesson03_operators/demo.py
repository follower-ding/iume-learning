# 整数分钟适合用来练习算术。
first = 20
second = 25
total = first + second
print("总分钟：", total)
print("相差：", second - first)
print("翻倍：", first * 2)
print("平均：", total / 2)
print("整段：", total // 20)
print("剩余：", total % 20)
print("平方：", 3 ** 2)
# 比较得到布尔值；逻辑运算组合条件。
print("达到目标：", total >= 40)
print("区间内：", total >= 30 and total <= 60)
print("需要休息：", total < 0 or total > 90)
print("尚未完成：", not (total >= 60))
print("先乘后加：", 2 + 3 * 4)
print("括号优先：", (2 + 3) * 4)
# 浮点数常常只能近似表示十进制小数。
print("浮点结果：", 0.1 + 0.2)
